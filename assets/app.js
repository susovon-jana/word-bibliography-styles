/* --------------------------------------------------------------- helpers */

const escapeHtml = (value) =>
  String(value).replace(/[&<>'"]/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "'": "&#39;", '"': "&quot;" })[c]
  );

function formatSize(bytes) {
  if (!Number.isFinite(bytes) || bytes <= 0) return "XSL";
  return `${Math.max(1, Math.round(bytes / 1024))} KB`;
}

function formatWhen(iso) {
  if (!iso) return "—";
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return "—";
  const mins = Math.round((Date.now() - date.getTime()) / 60000);
  if (mins < 1) return "just now";
  if (mins < 60) return `${mins} min ago`;
  const hours = Math.round(mins / 60);
  if (hours < 24) return `${hours} h ago`;
  return date.toLocaleDateString(undefined, { day: "numeric", month: "short", year: "numeric" });
}

function showToast(message) {
  if (!toast) return;
  toast.textContent = message;
  toast.classList.add("show");
  clearTimeout(showToast._timer);
  showToast._timer = setTimeout(() => toast.classList.remove("show"), 1800);
}

async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
  } catch (_) {
    const area = document.createElement("textarea");
    area.value = text;
    area.style.position = "fixed";
    area.style.opacity = "0";
    document.body.append(area);
    area.select();
    document.execCommand("copy");
    area.remove();
  }
}

/* -------------------------------------------------- auto metadata (layer 3) */

function humanizeFilename(file) {
  let base = file.replace(/\.(xsl)$/i, "");
  base = base
    .replace(/OfficeOnline/gi, "")
    .replace(/Nmerical/g, " Numerical")
    .replace(/([a-z\d])([A-Z])/g, "$1 $2")
    .replace(/[_\-.]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  return base || file;
}

function guessCategory(file) {
  const f = file.toLowerCase();
  if (/(^|[^a-z])doi([^a-z]|$)/.test(f)) return "custom";
  if (/apa|harvard|mla|chicago|turabian|sist/.test(f)) return "author-date";
  if (/ieee|iso690|iso ?690|gb|gost|numeric/.test(f)) return "numeric";
  return "general";
}

const CATEGORY_LABELS = {
  "author-date": "Author–date",
  numeric: "Numeric",
  custom: "Custom",
  general: "General",
};

function autoEntry(fileName, extras = {}) {
  const category = extras.category || guessCategory(fileName);
  return {
    file: fileName,
    name: humanizeFilename(fileName),
    wordName: humanizeFilename(fileName),
    category,
    categoryLabel: CATEGORY_LABELS[category] || CATEGORY_LABELS.general,
    summary: `Microsoft Word bibliography style. Download it and copy it into your Word bibliography styles folder.`,
    features: [
      "Compatible with Microsoft Word bibliography tools",
      "Downloadable XSL style file",
      "Installable in the Word styles folder",
    ],
    size: extras.size,
    downloadUrl: extras.downloadUrl,
    ...extras,
  };
}

/** Fetch the raw XSL and pull out the real Word display name. */
async function enrichFromXsl(entry) {
  const url = entry.downloadUrl || `${STYLES_DIR}/${encodeURIComponent(entry.file)}`;
  try {
    const res = await fetch(url, { cache: "no-store" });
    if (!res.ok) return;
    const xml = await res.text();
    const patterns = [
      /<xsl:when[^>]*test=["']b:StyleName["'][^>]*>\s*(?:<xsl:text>\s*)?([^<]+?)(?:\s*<\/xsl:text>)?\s*<\/xsl:when>/,
      /<b:StyleName[^>]*>([^<]+)<\/b:StyleName>/,
      /b:Lcid=["']1033["'][^>]*>\s*(?:<xsl:text>\s*)?([^<]+?)(?:\s*<\/xsl:text>)/,
    ];
    let wordName = null;
    for (const re of patterns) {
      const m = xml.match(re);
      if (m && m[1]) { wordName = m[1].trim().replace(/\s+/g, " "); break; }
    }
    if (wordName) {
      entry.wordName = wordName;
      if (!entry._hasMetadata) {
        entry.name = humanizeFilename(entry.file) === entry.name ? wordName : entry.name;
      }
      renderStyles();
      updateCounts();
    }
  } catch (_) { /* offline or blocked — filename stays */ }
}

/* ------------------------------------------------------- loaders (layers 1-2) */

async function fetchLiveFromGitHub() {
  const url = `https://api.github.com/repos/${REPO}/contents/${STYLES_DIR}`;
  const res = await fetch(url, {
    headers: { Accept: "application/vnd.github+json" },
    cache: "no-store",
  });
  if (!res.ok) throw new Error(`GitHub API responded ${res.status}`);
  const entries = await res.json();
  if (!Array.isArray(entries)) throw new Error("Unexpected GitHub API response");
  const files = entries
    .filter((e) => e.type === "file" && /\.xsl$/i.test(e.name))
    .map((e) => ({
      file: e.name,
      size: e.size,
      downloadUrl: e.download_url,
    }));
  if (!files.length) throw new Error("No .xsl files reported by GitHub");
  return files;
}

async function fetchCatalog() {
  const res = await fetch(`${STYLES_DIR}/index.json?v=${Date.now()}`, { cache: "no-store" });
  if (!res.ok) throw new Error("Catalog unavailable");
  const data = await res.json();
  if (Array.isArray(data)) return { generated: null, styles: data };
  return data;
}

function setSyncState(state, html) {
  syncRow.dataset.state = state;
  syncDot.className = `sync-dot`;
  syncText.innerHTML = html;
}

/* ------------------------------------------------------------ main loader */

async function loadStyles() {
  loadingNote && (grid.innerHTML = `<p class="loading">Scanning the styles folder…</p>`);

  let liveFiles = null;
  let catalog = null;

  const livePromise = fetchLiveFromGitHub()
    .then((files) => {
      liveFiles = files;
      return files;
    })
    .catch((error) => {
      console.info("[styles] GitHub API layer skipped:", error.message);
      return null;
    });

  const catalogPromise = fetchCatalog()
    .then((data) => {
      catalog = data;
      return data;
    })
    .catch((error) => {
      console.info("[styles] catalog layer skipped:", error.message);
      return null;
    });

  await Promise.all([livePromise, catalogPromise]);

  if (!liveFiles && !catalog) {
    grid.innerHTML =
      '<p class="loading">The style list could not be loaded. Check your connection and <button class="filter" id="retry-load" type="button">try again</button>.</p>';
    document.querySelector("#retry-load")?.addEventListener("click", loadStyles);
    setSyncState("offline", "Could not reach GitHub — <strong>offline</strong>");
    return;
  }

  const metaMap = new Map((catalog?.styles || []).map((s) => [s.file, s]));

  let merged;
  if (liveFiles) {
    /* Layer 1 wins: every .xsl in the repo, enriched with catalog metadata */
    merged = liveFiles.map((f) => {
      const meta = metaMap.get(f.file);
      if (meta) return { ...autoEntry(f.file, f), ...meta, _hasMetadata: true, downloadUrl: f.downloadUrl || meta.downloadUrl };
      return autoEntry(f.file, f);
    });
    const unknown = merged.filter((s) => !metaMap.has(s.file));
    setSyncState(
      "live",
      `<strong>Live from GitHub</strong> · ${unknown.length ? unknown.length + " new file(s) picked up" : "in sync with repository"}`
    );
    if (unknown.length) unknown.forEach((entry) => enrichFromXsl(entry));
  } else {
    /* Layer 2: catalog only */
    merged = (catalog?.styles || []).map((s) => ({ ...autoEntry(s.file), ...s, _hasMetadata: true }));
    setSyncState(
      "catalog",
      `<strong>Catalog mode</strong> · GitHub API rate limit reached, list still complete`
    );
  }

  if (catalog?.generated) statUpdated.textContent = formatWhen(catalog.generated);

  styles = merged.sort((a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base" }));
  buildFilters();
  updateCounts();
  renderStyles();
}

/* ------------------------------------------------------------- rendering */

function buildFilters() {
  const present = [...new Set(styles.map((s) => s.category))];
  const order = ["all", "author-date", "numeric", "custom", "general"].filter(
    (c) => c === "all" || present.includes(c)
  );
  const labels = { all: "All styles", ...CATEGORY_LABELS };
  if (!order.includes(activeFilter)) activeFilter = "all";
  filterBar.replaceChildren(
    ...order.map((cat) => {
      const button = document.createElement("button");
      button.className = `filter${cat === activeFilter ? " active" : ""}`;
      button.dataset.filter = cat;
      button.type = "button";
      button.textContent = labels[cat] || cat;
      return button;
    })
  );
}

function updateCounts() {
  const target = styles.length;
  animateCount(totalEl, target);
  chipCount.textContent = target;
  const cats = new Set(styles.map((s) => s.category)).size;
  statCategories.textContent = cats;
}

function animateCount(el, target) {
  if (countAnimation) cancelAnimationFrame(countAnimation);
  const from = Number(el.textContent) || 0;
  if (from === target) { el.textContent = target; return; }
  const duration = 900;
  const start = performance.now();
  const tick = (now) => {
    const t = Math.min(1, (now - start) / duration);
    const eased = 1 - Math.pow(1 - t, 3);
    el.textContent = Math.round(from + (target - from) * eased);
    if (t < 1) countAnimation = requestAnimationFrame(tick);
  };
  countAnimation = requestAnimationFrame(tick);
}

function renderStyles() {
  const term = search.value.trim().toLowerCase();
  const visible = styles.filter((style) => {
    const matchesFilter = activeFilter === "all" || style.category === activeFilter;
    const haystack = `${style.name} ${style.file} ${style.wordName} ${style.summary} ${style.features.join(" ")} ${style.categoryLabel}`.toLowerCase();
    return matchesFilter && haystack.includes(term);
  });

  resultCount.textContent = `Showing ${visible.length} of ${styles.length} styles`;

  if (!visible.length) {
    grid.innerHTML =
      '<p class="loading">No styles match that search. Try a different name, or reset the filters.</p>';
    return;
  }

  grid.replaceChildren();
  visible.forEach((style, index) => {
    const card = cardTemplate.content.cloneNode(true);
    const article = card.querySelector("article");
    article.style.animationDelay = `${Math.min(index * 45, 380)}ms`;
    card.querySelector(".style-category").textContent = style.categoryLabel;
    card.querySelector(".style-name").textContent = style.name;
    card.querySelector(".style-summary").textContent = style.summary;
    card.querySelector(".feature-list").replaceChildren(
      ...style.features.slice(0, 3).map((feature) => {
        const li = document.createElement("li");
        li.textContent = feature;
        return li;
      })
    );
    const download = card.querySelector(".download-button");
    const href = style.downloadUrl || `${STYLES_DIR}/${encodeURIComponent(style.file)}`;
    download.href = href;
    download.setAttribute("download", style.file);
    card.querySelector(".details-button").addEventListener("click", () => showDetails(style));
    grid.append(card);
  });
}

