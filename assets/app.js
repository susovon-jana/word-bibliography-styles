/* ==========================================================================
   Word Citation Styles — app
   Three-layer auto-updating style discovery:

     Layer 1 (live)   : GitHub Contents API lists styles/ directly from the
                        repository, so any .xsl pushed to GitHub appears here
                        on the very next page load — no rebuild required.
     Layer 2 (build)  : styles/index.json is regenerated by the deploy
                        workflow on every push (scripts/generate-catalog.mjs).
     Layer 3 (auto)   : files that are not in the catalog yet get their real
                        Word display name parsed client-side straight from the
                        XSL (b:StyleName / b:StyleNameLocalized).

   The visible count, cards and filters are always computed from data —
   nothing is hard-coded.
   ========================================================================== */

