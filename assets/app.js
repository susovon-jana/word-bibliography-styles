/* ------------------------------------------------------------------ config */

const FALLBACK_REPO = "susovon-jana/word-bibliography-styles";
const STYLES_DIR = "styles";
const WORD_STYLE_PATHS = {
  windows: "%APPDATA%\\Microsoft\\Bibliography\\Style",
  mac: "~/Library/Containers/com.microsoft.Word/Data/Documents/Bibliography/Style",
};

function detectRepo() {
  try {
    if (location.hostname.endsWith(".github.io")) {
      const owner = location.hostname.split(".")[0];
      const first = location.pathname.split("/").filter(Boolean)[0];
      if (owner && first) return `${owner}/${first}`;
    }
  } catch (_) { /* non-browser edge cases */ }
  return FALLBACK_REPO;
}

